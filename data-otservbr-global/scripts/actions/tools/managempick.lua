local config = {
    price_percent = 100, -- how many % of shop price player receive when sell by 'item seller'
    --cash_to_bank = true -- send money to bank, not add to player BP
}

local shopItems = {}
local itemLootSeller = Action()
function itemLootSeller.onUse(player, item, fromPosition, target, toPosition, isHotkey)
    if toPosition.x ~= 65535 and getDistanceBetween(player:getPosition(), toPosition) > 1 then
      player:sendTextMessage(MESSAGE_EVENT_ADVANCE, 'This item is too far away.')
		return true
    end

    local targetTile = Tile(toPosition)
    if targetTile then
        -- this is to prevent selling item that lays in house doors
        local targetHouse = targetTile:getHouse()
        if targetHouse then
            -- this blocks only selling items laying on house floor
            -- if player open BP that lays on house floor, he can sell items inside it
            player:sendTextMessage(MESSAGE_EVENT_ADVANCE, 'You cannot sell items in house.')
            return true
        end
    end

    local itemEx = Item(target.uid)
    if not itemEx then
        player:sendTextMessage(MESSAGE_EVENT_ADVANCE, 'This is not an item.')
        return true
    end

    if itemEx:getUniqueId() < 65535 or itemEx:getActionId() > 0 then
        player:sendTextMessage(MESSAGE_EVENT_ADVANCE, 'You cannot sell quest item.')
        return true
    end

    if not shopItems[itemEx.itemid] then
        player:sendTextMessage(MESSAGE_EVENT_ADVANCE, 'This is not sellable item.')
        return true
    end

    local itemCount = 1
    local itemType = ItemType(itemEx.itemid)
    if itemType:isStackable() then
        itemCount = itemEx.type
    end

    local itemName = itemEx:getName()
    local itemValue = math.ceil(shopItems[itemEx.itemid] * itemCount / 100 * config.price_percent)
    if itemValue > 0 then
        itemEx:getPosition():sendMagicEffect(CONST_ME_GIFT_WRAPS)
        itemEx:remove()
		local message = 'You destroyed ' .. itemCount .. ' ' .. itemName .. ' for ' .. itemValue * 10 .. 'k gold pieces value in tokens.'		
			if itemValue >= 1000 then 
			value = itemValue / 100 
			player:addItem(22723, value)-- platinum tokens	
			elseif itemValue <= 99 then
			player:addItem(22516, itemValue)-- silver tokens
			else
			value = itemValue / 10 
			player:addItem(22721, value)-- gold token		
			end
	player:sendTextMessage(MESSAGE_EVENT_ADVANCE, message)
    else
        player:sendTextMessage(MESSAGE_EVENT_ADVANCE, itemName .. ' is worthless.')
    end

    return true
end

itemLootSeller:id(32711)
itemLootSeller:register()

